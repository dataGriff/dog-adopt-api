#!/usr/bin/env node
// Writes migrations/0002_seed_reference_data.sql from the seed data shipped
// in @dogadopt/contracts. Run after bumping the contracts package; commit
// the result. Rescue ids are fixed in the seed so re-running is stable.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const rescues = require('@dogadopt/contracts/seed/rescues.json');
const breeds = require('@dogadopt/contracts/seed/breeds.json');
const out = new URL('../migrations/0002_seed_reference_data.sql', import.meta.url);

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const SEEDED_AT = '2026-10-19T00:00:00.000Z';

const lines = [
  '-- Generated by scripts/build-seed-migration.mjs from @dogadopt/contracts seed data. Do not edit by hand.',
  '',
];
for (const r of rescues) {
  lines.push(
    `INSERT INTO rescues (id, name, type, region, website, phone, email, address, postcode, charity_number, contact_notes, latitude, longitude, created_at, updated_at) VALUES (${[
      r.id, r.name, r.type, r.region, r.website, r.phone, r.email, r.address, r.postcode, r.charityNumber, null, r.latitude, r.longitude, SEEDED_AT, SEEDED_AT,
    ].map(q).join(', ')});`,
  );
}
lines.push('');
for (const b of breeds) lines.push(`INSERT INTO breeds (name) VALUES (${q(b.name)});`);
lines.push('');
// A synonym that only differs from a canonical name by case is dropped:
// canonical names already resolve case-insensitively, and the contract says
// no synonym may appear as a canonical name.
const canonical = new Set(breeds.map((b) => b.name.toLowerCase()));
let synonymCount = 0;
for (const b of breeds) {
  for (const s of b.synonyms) {
    if (canonical.has(s.toLowerCase())) continue;
    synonymCount++;
    lines.push(`INSERT INTO breed_synonyms (synonym, breed_name) VALUES (${q(s)}, ${q(b.name)});`);
  }
}
lines.push('');

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${rescues.length} rescues, ${breeds.length} breeds, ${synonymCount} synonyms to migrations/0002_seed_reference_data.sql`);
