#!/usr/bin/env node
// Writes seed/reference-data.sql from the seed data shipped in
// @dogadopt/contracts. The file is idempotent: rescues are upserted on their
// fixed id, breeds and synonyms are inserted if missing. Apply it after the
// migrations, locally and remotely, as often as you like. Run this after
// bumping the contracts package and commit the result; CI checks for drift.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const rescues = require('@dogadopt/contracts/seed/rescues.json');
const breeds = require('@dogadopt/contracts/seed/breeds.json');
const out = new URL('../seed/reference-data.sql', import.meta.url);

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const SEEDED_AT = '2026-10-19T00:00:00.000Z';

const lines = [
  '-- Generated by scripts/build-seed.mjs from @dogadopt/contracts seed data. Do not edit by hand.',
  '-- Idempotent: safe to apply to a database that already holds any of these rows.',
  '',
];
for (const r of rescues) {
  const values = [r.id, r.name, r.type, r.region, r.website, r.phone, r.email, r.address, r.postcode, r.charityNumber, null, r.latitude, r.longitude, SEEDED_AT, SEEDED_AT].map(q).join(', ');
  lines.push(
    `INSERT INTO rescues (id, name, type, region, website, phone, email, address, postcode, charity_number, contact_notes, latitude, longitude, created_at, updated_at) VALUES (${values}) ON CONFLICT(id) DO UPDATE SET name = excluded.name, type = excluded.type, region = excluded.region, website = excluded.website, phone = excluded.phone, email = excluded.email, address = excluded.address, postcode = excluded.postcode, charity_number = excluded.charity_number, latitude = excluded.latitude, longitude = excluded.longitude, updated_at = CASE WHEN rescues.name IS excluded.name AND rescues.type IS excluded.type AND rescues.region IS excluded.region AND rescues.website IS excluded.website AND rescues.phone IS excluded.phone AND rescues.email IS excluded.email AND rescues.address IS excluded.address AND rescues.postcode IS excluded.postcode AND rescues.charity_number IS excluded.charity_number AND rescues.latitude IS excluded.latitude AND rescues.longitude IS excluded.longitude THEN rescues.updated_at ELSE excluded.updated_at END;`,
  );
}
lines.push('');
for (const b of breeds) lines.push(`INSERT OR IGNORE INTO breeds (name) VALUES (${q(b.name)});`);
lines.push('');
// A synonym that only differs from a canonical name by case is dropped:
// canonical names already resolve case-insensitively, and the contract says
// no synonym may appear as a canonical name.
const canonical = new Set(breeds.map((b) => b.name.toLowerCase()));
let synonymCount = 0;
for (const b of breeds) {
  for (const s of b.synonyms) {
    if (canonical.has(s.toLowerCase())) continue;
    synonymCount++;
    lines.push(`INSERT OR IGNORE INTO breed_synonyms (synonym, breed_name) VALUES (${q(s)}, ${q(b.name)});`);
  }
}
lines.push('');

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${rescues.length} rescues, ${breeds.length} breeds, ${synonymCount} synonyms to seed/reference-data.sql`);
